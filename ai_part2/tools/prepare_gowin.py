"""Export a checked 6-8-3 model as a self-contained Gowin synthesis project."""
import argparse,hashlib,json,math,re,shutil,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import numpy as np
from part2.integer import infer


def validate(model_dir):
    model_dir=Path(model_dir)
    m=json.loads((model_dir/'model.json').read_text())
    if m['architecture'] != [6,8,3]:raise ValueError('Only architecture 6-8-3 is supported')
    for key,shape,bits in [('w1',(8,6),8),('w2',(3,8),8),('b1',(8,),32),('b2',(3,),32)]:
        a=np.asarray(m[key])
        if a.shape!=shape or a.dtype.kind not in 'iu':raise ValueError(f'Invalid {key}')
        if (a<-(1<<(bits-1))).any() or (a>=(1<<(bits-1))).any():raise ValueError(f'{key} out of range')
        raw=[int(x,16) for x in (model_dir/(key+'.hex')).read_text().split()]
        if raw!=[int(v)&((1<<bits)-1) for v in a.flat]:raise ValueError(f'{key}.hex differs from model.json')
    if len(m['divisors'])!=6 or any(not isinstance(d,int) or d<1 or d&(d-1) for d in m['divisors']):
        raise ValueError('Six power-of-two divisors are required')
    if any(not isinstance(m[k],int) or not 0<=m[k]<=31 for k in ('shift1','shift2')):
        raise ValueError('Invalid shifts')
    for wk,bk in [('w1','b1'),('w2','b2')]:
        bound=127*np.abs(np.asarray(m[wk],dtype=np.int64)).sum(axis=1)+np.abs(np.asarray(m[bk],dtype=np.int64))
        if int(bound.max())>=2**31:raise ValueError('Accumulator bound exceeds int32')
    features=[];expected=[];classes=[]
    for n,line in enumerate((model_dir/'vectors.txt').read_text().splitlines(),1):
        a,b,c=line.split();feat=int(a,16);score=int(b,16);cls=int(c)
        if not 0<=feat<2**48 or not 0<=score<2**48 or cls not in (0,1,2):raise ValueError(f'Bad vector {n}')
        x=[(feat>>(8*i))&255 for i in range(6)]
        if max(x)>127:raise ValueError(f'Input outside 0..127 at vector {n}')
        features.append(x);expected.append([(score>>(16*i))&65535 for i in range(3)]);classes.append(cls)
    if not features:raise ValueError('No verification vectors')
    scores=infer(features,m)
    if not np.array_equal(scores&65535,expected) or not np.array_equal(scores.argmax(axis=1),classes):
        raise ValueError('Vectors do not match integer model')
    return m,len(features)


def rom_function(name,values,bits,addr_bits):
    flat=np.asarray(values).reshape(-1)
    lines=[f'    function signed [{bits-1}:0] {name};',f'        input [{addr_bits-1}:0] addr;',
           '        begin','            case (addr)']
    for i,v in enumerate(flat):lines.append(f"                {addr_bits}'d{i}: {name} = {bits}'sh{int(v)&((1<<bits)-1):0{bits//4}x};")
    lines += [f"                default: {name} = {bits}'sd0;",'            endcase','        end','    endfunction','']
    return '\n'.join(lines)


def standalone(source,m):
    source=source.replace('Load memory files from the model working directory.', 'ROM constants embedded below.')
    source=source.replace('`include "quant_params.vh"','// Quantization and weights embedded for this exact model.')
    source,n=re.subn(r'module ai_core #\(.*?\)\(', 'module ai_core (',source,count=1,flags=re.S)
    if n!=1:raise ValueError('Unrecognized ai_core module header')
    source=source.replace('    reg signed [7:0] w1 [0:47], w2 [0:23];\n','')
    source=source.replace('    reg signed [31:0] b1 [0:7], b2 [0:2];\n','')
    source,n=re.subn(r'    initial begin\n.*?\$readmemh.*?    end\n','',source,count=1,flags=re.S)
    if n!=1:raise ValueError('Unrecognized ROM initializer')
    for a,b in [('w1[neuron*6+idx]','rom_w1(neuron*6+idx)'),('w2[neuron*8+idx]','rom_w2(neuron*8+idx)'),
                ('b1[neuron]','rom_b1(neuron)'),('b2[neuron]','rom_b2(neuron)')]:source=source.replace(a,b)
    source=source.replace('`SHIFT1',str(m['shift1'])).replace('`SHIFT2',str(m['shift2']))
    funcs='\n'.join(rom_function('rom_'+k,m[k],bits,addr) for k,bits,addr in [('w1',8,6),('w2',8,5),('b1',32,3),('b2',32,2)])
    source=source.replace('    always @* begin',funcs+'\n    always @* begin',1)
    if '$readmemh' in source or '`include' in source:raise ValueError('Export still has external dependencies')
    return '// Generated by prepare_gowin.py. Do not mix with another model.\n'+source


def firmware_header(m):
    shifts=[int(math.log2(d)) for d in m['divisors']]
    lines=['#ifndef AI_QUANT_V1_H','#define AI_QUANT_V1_H','#include <stdint.h>',
           '/* Raw feature order and semantics: see spec/FEATURES_V0.md. */',
           'static inline uint8_t ai_v1_clip(uint64_t x) { return x > 127u ? 127u : (uint8_t)x; }',
           'static inline uint64_t ai_v1_pack(uint32_t packets, uint64_t ip_bytes, uint32_t syn_open,',
           '                                  uint32_t src_count, uint32_t dst_count, uint32_t port_count) {',
           '    if (!packets) return 0;',
           '    uint64_t raw[6] = {packets, ip_bytes / packets,',
           '                       (127ull * syn_open) / packets, src_count, dst_count, port_count};',
           '    uint64_t feat = 0;']
    for i,shift in enumerate(shifts):lines.append(f'    feat |= (uint64_t)ai_v1_clip(raw[{i}] >> {shift}) << {i*8};')
    lines += ['    return feat;','}','#endif','']
    return '\n'.join(lines)


def prepare(model_dir,out,kit):
    model_dir,out,kit=Path(model_dir),Path(out),Path(kit)
    m,count=validate(model_dir)
    if out.exists():raise ValueError('Output directory exists; choose a new path')
    for d in ('src','constraints','verification','firmware','reference'): (out/d).mkdir(parents=True,exist_ok=True)
    generated=standalone((kit/'rtl/ai_core.v').read_text(),m)
    (out/'src/ai_core_model_v1.v').write_text(generated)
    (out/'constraints/ai_core.sdc').write_text('create_clock -name clk_ai -period 37.037 [get_ports {clk}]\n')
    (out/'firmware/ai_quant_v1.h').write_text(firmware_header(m))
    shutil.copy2(kit/'sim/tb_ai_core.v',out/'verification/tb_ai_core.v')
    shutil.copy2(model_dir/'vectors.txt',out/'verification/vectors.txt')
    shutil.copy2(model_dir/'model.json',out/'reference/model.json')
    if (model_dir/'metrics.json').exists():shutil.copy2(model_dir/'metrics.json',out/'reference/metrics.json')
    project='''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE gowin-fpga-project>
<Project>
    <Template>FPGA</Template>
    <Version>5</Version>
    <Device name="GW1NR-9C" pn="GW1NR-LV9QN88PC6/I5">gw1nr9c-004</Device>
    <FileList>
        <File path="src/ai_core_model_v1.v" type="file.verilog" enable="1"/>
        <File path="constraints/ai_core.sdc" type="file.sdc" enable="1"/>
    </FileList>
</Project>
'''
    (out/'ai_core_v1.gprj').write_text(project)
    tcl='''# Standalone synthesis only. No pin assignment or board programming.
set root [file normalize [file dirname [info script]]]
cd $root
set_device GW1NR-LV9QN88PC6/I5 -device_version C
add_file [file join $root src ai_core_model_v1.v]
add_file [file join $root constraints ai_core.sdc]
set_option -top_module ai_core
set_option -output_base_name ai_core_v1
run syn
'''
    (out/'synth_ai.tcl').write_text(tcl)
    (out/'verification/run_sim.sh').write_text('''#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p verification/build
iverilog -g2012 -Wall -s tb_ai_core -o verification/build/sim.vvp src/ai_core_model_v1.v verification/tb_ai_core.v
vvp verification/build/sim.vvp +vectors=verification/vectors.txt | tee verification/build/result.log
grep -q '^PASS vectors=' verification/build/result.log
''')
    manifest={'model_sha256':hashlib.sha256((model_dir/'model.json').read_bytes()).hexdigest(),
              'rtl_sha256':hashlib.sha256(generated.encode()).hexdigest(),
              'vector_count':count,'architecture':m['architecture'],'divisors':m['divisors'],
              'shifts':[m['shift1'],m['shift2']],
              'status':'Generated; validate simulation. Gowin synthesis/timing not executed by this generator.',
              'device_template_reference':'https://github.com/sipeed/TangNano-9K-example/blob/c3b795799f23de91982be52db4273a8eea100cdb/led/9K_LED_project.gprj'}
    (out/'EXPORT_MANIFEST.json').write_text(json.dumps(manifest,indent=2))
    return manifest

